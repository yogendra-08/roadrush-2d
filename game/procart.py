def make_icon(name: str, size: int = 28) -> Image.Image:
    img, d = _canvas(size, size)
    W = size * SS
    if name in ("heart", "heart_empty"):
        fill = (232, 48, 80, 255) if name == "heart" else (60, 66, 88, 255)
        r = W * 0.26
        d.ellipse([W * 0.08, W * 0.14, W * 0.08 + 2 * r, W * 0.14 + 2 * r], fill=fill)
        d.ellipse([W * 0.92 - 2 * r, W * 0.14, W * 0.92, W * 0.14 + 2 * r], fill=fill)
        d.polygon([(W * 0.09, W * 0.42), (W * 0.91, W * 0.42), (W * 0.5, W * 0.9)], fill=fill)
    elif name == "coin":
        d.ellipse([W * 0.06, W * 0.06, W * 0.94, W * 0.94], fill=(150, 100, 6, 255))
        d.ellipse([W * 0.14, W * 0.14, W * 0.86, W * 0.86], fill=(255, 206, 40, 255))
        d.ellipse([W * 0.3, W * 0.3, W * 0.7, W * 0.7], outline=(214, 150, 10, 255), width=SS * 2)
    elif name == "fuel":
        d.rounded_rectangle([W * 0.2, W * 0.28, W * 0.8, W * 0.92], radius=W * 0.1, fill=(222, 52, 52, 255))
        d.rectangle([W * 0.38, W * 0.12, W * 0.62, W * 0.3], fill=(70, 70, 78, 255))
        d.ellipse([W * 0.36, W * 0.46, W * 0.64, W * 0.78], fill=(250, 250, 250, 255))
    elif name == "nitro":
        d.polygon([(W * 0.58, W * 0.04), (W * 0.2, W * 0.56), (W * 0.46, W * 0.56), (W * 0.36, W * 0.96),
                   (W * 0.8, W * 0.4), (W * 0.54, W * 0.4)], fill=(60, 190, 255, 255))
    elif name == "app":
        base = make_car_preview("sports").resize((W // 2, W), Image.LANCZOS)
        img.alpha_composite(base, ((W - base.width) // 2, 0))
    return _down(img, size, size)
