    d = ImageDraw.Draw(img)
    # rear wing
    d.rounded_rectangle([cx - 82, bot - 44, cx + 82, bot - 10], radius=7, fill=black + (255,))
    for sx in (-1, 1):
        d.rectangle([cx + sx * 78 - 5, bot - 48, cx + sx * 78 + 5, bot - 6], fill=yellow + (255,))
